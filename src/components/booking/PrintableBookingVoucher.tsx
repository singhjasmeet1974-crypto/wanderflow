import React from 'react';
import { Booking } from '../../types';
import { Compass, Printer, X, CheckCircle2 } from 'lucide-react';


interface PrintableBookingVoucherProps {
  booking: Booking;
  onClose: () => void;
}

export const PrintableBookingVoucher: React.FC<PrintableBookingVoucherProps> = ({
  booking,
  onClose,
}) => {
  const handlePrint = () => {
    window.print();
  };

  const checkInFormatted = new Date(`${booking.checkIn}T00:00:00`).toLocaleDateString('en-US', {
    weekday: 'short',
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  });
  const checkOutFormatted = new Date(`${booking.checkOut}T00:00:00`).toLocaleDateString('en-US', {
    weekday: 'short',
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  });

  return (
    <div
      role="dialog"
      aria-modal="true"
      aria-label="Booking voucher summary"
      className="fixed inset-0 z-50 overflow-y-auto bg-stone-900/80 backdrop-blur-xs flex items-center justify-center p-3 sm:p-6 print:p-0 print:bg-white animate-in fade-in duration-150"
    >
      <div className="relative w-full max-w-2xl bg-white rounded-3xl shadow-2xl border border-stone-200 overflow-hidden print:shadow-none print:border-none print:rounded-none">
        {/* Floating Print & Close Bar (Hidden on actual print) */}
        <div className="p-4 bg-stone-900 text-white flex items-center justify-between print:hidden">
          <div className="flex items-center gap-2 text-xs">
            <span className="w-2 h-2 rounded-full bg-[#E5A43B]"></span>
            <span className="font-semibold">Printable Demo Booking Summary</span>
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="px-4 py-1.5 rounded-lg bg-[#E0704D] hover:bg-[#cb5b38] text-white text-xs font-bold transition flex items-center gap-1.5 cursor-pointer shadow-xs"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>Print / Save PDF</span>
            </button>
            <button
              onClick={onClose}
              className="p-1.5 rounded-lg hover:bg-stone-800 text-stone-300 hover:text-white transition cursor-pointer"
              aria-label="Close printable voucher"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Voucher Body */}
        <div className="p-6 sm:p-10 space-y-6 text-stone-900 bg-[#FAF9F6] print:bg-white print:p-8">
          {/* Header with Logo and Reference */}
          <div className="flex items-start justify-between pb-6 border-b-2 border-[#16382B]">
            <div className="flex items-center gap-3">
              <div className="w-12 h-12 rounded-2xl bg-[#16382B] text-white flex items-center justify-center">
                <Compass className="w-6 h-6 text-[#E5A43B]" />
              </div>
              <div>
                <h1 className="text-2xl font-bold font-editorial text-[#16382B] flex items-center gap-1">
                  Wanderflow
                  <span className="w-1.5 h-1.5 rounded-full bg-[#E0704D]"></span>
                </h1>
                <p className="text-[10px] text-stone-500 uppercase tracking-widest font-semibold">
                  TR-101 Training Evaluation Voucher
                </p>
              </div>
            </div>

            <div className="text-right">
              <span className="text-[10px] font-bold text-stone-500 uppercase tracking-wider block">
                Booking Reference
              </span>
              <span className="font-mono text-base sm:text-lg font-bold text-[#16382B] bg-stone-100 px-2 py-0.5 rounded border border-stone-300 block">
                {booking.bookingReference}
              </span>
              <span className="text-[10px] text-stone-500 mt-1 block">
                Issued: {new Date(booking.createdAt).toLocaleDateString()}
              </span>
            </div>
          </div>

          {/* Watermark / Demo Callout */}
          <div className="p-3 rounded-xl bg-amber-50 border border-amber-300 text-center text-xs text-amber-950 font-medium">
            <span className="font-bold uppercase tracking-wider text-amber-900 block text-[11px]">
              ⚠️ Demonstration Booking Summary — Not a Commercial Reservation
            </span>
            <span className="text-[10px] text-amber-800">
              Generated by Wanderflow for TR-101 college project evaluation. No real hotel inventory held.
            </span>
          </div>

          {/* Accommodation & Destination Info */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 pb-6 border-b border-stone-200">
            <div>
              <span className="text-[10px] uppercase font-bold text-stone-500 block mb-1">
                Accommodation &amp; Location
              </span>
              <h2 className="text-xl font-bold font-editorial text-stone-900">
                {booking.accommodationName}
              </h2>
              <p className="text-xs text-stone-600 mt-0.5">
                {booking.destinationLocation || booking.destinationName}
              </p>
              {booking.roomType && (
                <span className="inline-block mt-2 text-xs font-semibold px-2 py-0.5 rounded bg-stone-100 text-stone-800 border border-stone-200">
                  {booking.roomType}
                </span>
              )}
            </div>

            <div className="space-y-1 sm:text-right">
              <span className="text-[10px] uppercase font-bold text-stone-500 block">
                Status
              </span>
              <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-bold bg-emerald-100 text-emerald-800 border border-emerald-300">
                <CheckCircle2 className="w-3.5 h-3.5" />
                <span>{booking.status} — Demo</span>
              </span>
              <p className="text-[11px] text-stone-500 pt-1">
                {booking.rooms} {booking.rooms === 1 ? 'Room' : 'Rooms'} • {booking.nights} {booking.nights === 1 ? 'Night' : 'Nights'}
              </p>
            </div>
          </div>

          {/* Travel Dates & Guest Particulars */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs pb-6 border-b border-stone-200">
            <div>
              <span className="text-stone-500 uppercase font-bold text-[10px] block">
                Check-In Date
              </span>
              <strong className="text-stone-900 block mt-0.5">{checkInFormatted}</strong>
              <span className="text-[10px] text-stone-400">After 01:00 PM</span>
            </div>

            <div>
              <span className="text-stone-500 uppercase font-bold text-[10px] block">
                Check-Out Date
              </span>
              <strong className="text-stone-900 block mt-0.5">{checkOutFormatted}</strong>
              <span className="text-[10px] text-stone-400">Before 11:00 AM</span>
            </div>

            <div>
              <span className="text-stone-500 uppercase font-bold text-[10px] block">
                Primary Traveler
              </span>
              <strong className="text-stone-900 block mt-0.5 truncate">
                {booking.guestDetails.fullName}
              </strong>
              <span className="text-[10px] text-stone-400 truncate block">
                {booking.guestDetails.email}
              </span>
            </div>

            <div>
              <span className="text-stone-500 uppercase font-bold text-[10px] block">
                Party Breakdown
              </span>
              <strong className="text-stone-900 block mt-0.5">
                {booking.guests.adults} Adults{booking.guests.children > 0 ? `, ${booking.guests.children} Children` : ''}
              </strong>
              <span className="text-[10px] text-stone-400">
                {booking.rooms} Room(s)
              </span>
            </div>
          </div>

          {/* Pricing Ledger */}
          <div className="space-y-2 text-xs">
            <span className="text-[10px] uppercase font-bold text-stone-500 tracking-wider block">
              Payment &amp; Demo Ledger
            </span>

            <div className="p-4 rounded-2xl bg-white border border-stone-200 space-y-2">
              <div className="flex justify-between text-stone-600">
                <span>
                  Stay Charge (₹{booking.priceBreakdown.nightlyRate.toLocaleString()} × {booking.nights}N × {booking.rooms}R)
                </span>
                <span className="font-semibold text-stone-900">
                  ₹{booking.priceBreakdown.baseAmount.toLocaleString()}
                </span>
              </div>

              <div className="flex justify-between text-stone-600">
                <span>Demo GST &amp; Tourism Service Fee (12%)</span>
                <span className="font-semibold text-stone-900">
                  ₹{booking.priceBreakdown.taxesAndFees.toLocaleString()}
                </span>
              </div>

              <div className="pt-2 border-t border-stone-200 flex justify-between text-base font-bold text-stone-900 font-editorial">
                <span>Total Demo Amount</span>
                <span className="text-[#16382B]">
                  ₹{booking.priceBreakdown.totalAmount.toLocaleString()}
                </span>
              </div>
            </div>
          </div>

          {/* Special Requests */}
          {booking.guestDetails.specialRequests && (
            <div className="p-3.5 rounded-xl bg-stone-100 text-xs text-stone-700">
              <span className="font-bold block text-[10px] text-stone-500 uppercase mb-0.5">
                Guest Requests:
              </span>
              <p className="italic">{booking.guestDetails.specialRequests}</p>
            </div>
          )}

          {/* Footer & Barcode Simulation */}
          <div className="pt-4 border-t border-dashed border-stone-300 flex flex-col sm:flex-row items-center justify-between gap-4 text-[10px] text-stone-500">
            <div className="space-y-0.5 text-center sm:text-left">
              <p className="font-semibold text-stone-700">
                Wanderflow Travel Discovery &amp; Itinerary Platform
              </p>
              <p>Guru Nanak Dev Engineering College, Ludhiana • Department of IT</p>
            </div>

            {/* Simulated Barcode */}
            <div className="flex flex-col items-center gap-1">
              <div className="flex items-center gap-0.5 h-7">
                {[4, 2, 5, 1, 3, 6, 2, 4, 1, 5, 3, 2, 6, 3, 4, 1, 5, 2, 4, 3, 2, 5, 1, 4].map(
                  (w, i) => (
                    <div
                      key={i}
                      className="bg-stone-900 h-full"
                      style={{ width: `${w}px` }}
                    />
                  )
                )}
              </div>
              <span className="font-mono text-[9px] tracking-wider text-stone-600">
                {booking.bookingReference}
              </span>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
